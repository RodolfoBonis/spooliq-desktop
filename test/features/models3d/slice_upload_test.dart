import 'dart:convert';
import 'dart:io';

import 'package:archive/archive.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:path/path.dart' as p;
import 'package:spooliq_desktop/features/models3d/data/slice_upload.dart';

void main() {
  late Directory dir;

  setUp(() => dir = Directory.systemTemp.createTempSync('slice-upload-test-'));
  tearDown(() => dir.deleteSync(recursive: true));

  String writeZip(String name, Map<String, List<int>> entries) {
    final archive = Archive();
    for (final e in entries.entries) {
      archive.addFile(ArchiveFile.bytes(e.key, e.value));
    }
    final file = File(p.join(dir.path, name))
      ..writeAsBytesSync(ZipEncoder().encodeBytes(archive));
    return file.path;
  }

  test('a sliced project keeps only the metadata the server reads', () {
    final path = writeZip('Concha.gcode.3mf', {
      'Metadata/slice_info.config': utf8.encode('<config><plate/></config>'),
      'Metadata/project_settings.config': utf8.encode('{}'),
      'Metadata/model_settings.config': utf8.encode('<config/>'),
      'Metadata/plate_1.gcode': List.filled(500000, 65),
      'Metadata/plate_1.png': List.filled(10000, 1),
      '3D/3dmodel.model': utf8.encode('<model/>'),
    });

    final slim = slimSlicedProject(path)!;
    expect(p.basename(slim), 'Concha.gcode.3mf', reason: 'name kept');
    final names = ZipDecoder()
        .decodeBytes(File(slim).readAsBytesSync())
        .files
        .map((f) => f.name)
        .toSet();
    expect(names, {
      'Metadata/slice_info.config',
      'Metadata/project_settings.config',
      'Metadata/model_settings.config',
    });
    File(slim).parent.deleteSync(recursive: true);
  });

  test('a project without slice_info is sent as is', () {
    final path = writeZip('design.3mf', {
      '3D/3dmodel.model': utf8.encode('<model/>'),
    });
    expect(slimSlicedProject(path), isNull);
  });

  test('a big G-code keeps only its head and tail', () {
    const mb = 1024 * 1024;
    final bytes = [
      ...utf8.encode('; generated by BambuStudio\n'),
      ...List.filled(5 * mb, 66), // middle the parser never reads
      ...utf8.encode('\n; total filament used [g] = 12.3\n'),
    ];
    final path = p.join(dir.path, 'big.gcode');
    File(path).writeAsBytesSync(bytes);

    final slim = gcodeHeadTail(path)!;
    final out = File(slim).readAsStringSync(encoding: latin1);
    expect(out, startsWith('; generated by BambuStudio'));
    expect(out, contains('total filament used [g] = 12.3'));
    expect(File(slim).lengthSync(), 2 * gcodeHeadTailBytes + 1);
    File(slim).parent.deleteSync(recursive: true);
  });

  test('small files are uploaded directly', () async {
    final path = writeZip('small.3mf', {
      'Metadata/slice_info.config': utf8.encode('<config/>'),
    });
    final upload = await prepareSliceUpload(path);
    expect(upload.path, path);
    expect(upload.temporary, isFalse);
    await upload.dispose();
    expect(File(path).existsSync(), isTrue, reason: 'never delete originals');
  });
}
